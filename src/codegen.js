import { startsOf } from './heading.js';

export const fmt = (n) => String(+Number(n).toFixed(3));
const pose = (p) => `new Pose(${fmt(p.x)}, ${fmt(p.y)})`;
const rad = (h) => `Math.toRadians(${fmt(h)})`;

export function javaIdent(name, fallback) {
  const words = String(name || '').replace(/[^A-Za-z0-9]+/g, ' ').trim().split(' ').filter(Boolean);
  if (!words.length) return fallback;
  let id = words.map((w, i) => (i ? w[0].toUpperCase() + w.slice(1) : w[0].toLowerCase() + w.slice(1))).join('');
  if (/^[0-9]/.test(id)) id = '_' + id;
  return id;
}

// Code for one chain, lines separated by \n, no leading indent on the first line.
export function chainBlock(fieldName, segments, startPose) {
  const out = [`${fieldName} = follower.pathBuilder()`];
  let cur = startPose;
  for (const seg of segments) {
    const pts = [cur, ...seg.controls, seg.end].map(pose);
    out.push(`    .addPath(new ${seg.controls.length ? 'BezierCurve' : 'BezierLine'}(${pts.join(', ')}))`);
    const m = seg.heading.mode;
    if (m === 'linear') out.push(`    .setLinearHeadingInterpolation(${rad(cur.h)}, ${rad(seg.end.h)})`);
    else if (m === 'constant') out.push(`    .setConstantHeadingInterpolation(${rad(seg.end.h)})`);
    else {
      out.push('    .setTangentHeadingInterpolation()');
      if (seg.heading.reverse) out.push('    .setReversed()');
    }
    cur = seg.end;
  }
  out.push('    .build();');
  return out.join('\n');
}

export function chainFieldNames(project) {
  const used = new Set();
  return project.chains.map((ch, i) => {
    let id = javaIdent(ch.name, `path${i + 1}`);
    while (used.has(id)) id += '_';
    used.add(id);
    return id;
  });
}

export function className(project) {
  const id = javaIdent(project.name, '');
  return id ? id[0].toUpperCase() + id.slice(1) + 'Paths' : 'AutoPaths';
}

export function generateJava(project) {
  const names = chainFieldNames(project);
  const starts = startsOf(project);
  const sp = project.startPose;
  const L = [];
  L.push('// Generated by Bubblotics Path Planner (Pedro Pathing v2)');
  L.push('import com.pedropathing.follower.Follower;');
  L.push('import com.pedropathing.geometry.BezierCurve;');
  L.push('import com.pedropathing.geometry.BezierLine;');
  L.push('import com.pedropathing.geometry.Pose;');
  L.push('import com.pedropathing.paths.PathChain;');
  L.push('');
  L.push(`public class ${className(project)} {`);
  L.push(`    public Pose startPose = new Pose(${fmt(sp.x)}, ${fmt(sp.y)}, ${rad(sp.h)});`);
  L.push('');
  names.forEach((n) => L.push(`    public PathChain ${n};`));
  L.push('');
  L.push('    public void buildPaths(Follower follower) {');
  project.chains.forEach((ch, i) => {
    if (!ch.segments.length) return;
    const block = chainBlock(names[i], ch.segments, starts[i][0]);
    L.push(...block.split('\n').map((l) => '        ' + l));
    if (i < project.chains.length - 1) L.push('');
  });
  L.push('    }');
  L.push('}');
  return L.join('\n') + '\n';
}
